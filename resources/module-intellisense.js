'use strict';

(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory;
    return;
  }

  const api = factory(root);
  root.NodeRedModuleIntellisense = api;
  api.register();
})(typeof globalThis !== 'undefined' ? globalThis : this, function (root) {
  const MODEL_DIRECTORY = 'file:///node/module/';
  const REGISTRY_URI = MODEL_DIRECTORY + 'registry.d.ts';
  const FUNCTION_TYPES_URI = 'file://types/node-red/func/index.d.ts';
  const FUNCTION_TYPES_PATH = 'types/node-red/func.d.ts';
  const MODULE_NAME_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
  const entries = Object.create(null);
  let registryLib = null;
  let registrySignature = '';
  let functionTypesSource = null;
  let functionTypesLib = null;
  let functionTypesRequest = null;
  let functionTypesTimer = null;
  let syncTimer = null;
  let registered = false;

  function editorHost() {
    return (
      root.RED &&
      root.RED.editor &&
      root.RED.editor.codeEditor &&
      root.RED.editor.codeEditor.editor
    );
  }

  function monacoReady() {
    const host = editorHost();
    return !!(
      root.monaco &&
      root.monaco.editor &&
      root.monaco.typescript &&
      root.monaco.typescript.javascriptDefaults &&
      host &&
      host.type === 'monaco'
    );
  }

  function workspaceFor(node) {
    if (!node || !node.z) {
      return undefined;
    }
    return root.RED.nodes.workspace(node.z) || root.RED.nodes.subflow(node.z);
  }

  function isActive(node) {
    const workspace = workspaceFor(node);
    return node.d !== true && (!workspace || workspace.disabled !== true);
  }

  function collectModules() {
    const candidates = [];
    const nameCounts = Object.create(null);

    root.RED.nodes.eachNode(function (node) {
      if (
        node.type !== 'module' ||
        !isActive(node) ||
        typeof node.moduleName !== 'string' ||
        !MODULE_NAME_PATTERN.test(node.moduleName) ||
        typeof node.func !== 'string'
      ) {
        return;
      }
      candidates.push(node);
      nameCounts[node.moduleName] = (nameCounts[node.moduleName] || 0) + 1;
    });

    return candidates
      .filter(function (node) {
        return nameCounts[node.moduleName] === 1;
      })
      .sort(function (left, right) {
        return left.moduleName.localeCompare(right.moduleName);
      });
  }

  function modelUriFor(nodeId) {
    return root.monaco.Uri.parse(MODEL_DIRECTORY + nodeId + '.js');
  }

  function disposeEntry(nodeId) {
    const entry = entries[nodeId];
    if (!entry) {
      return;
    }

    const host = editorHost();
    if (entry.retained && host && typeof host.releaseModel === 'function') {
      host.releaseModel(entry.uri);
    }
    if (entry.model && !entry.model.isDisposed()) {
      entry.model.dispose();
    }
    delete entries[nodeId];
  }

  function createEntry(node) {
    const uri = modelUriFor(node.id);
    const existingModel = root.monaco.editor.getModel(uri);
    const model =
      existingModel || root.monaco.editor.createModel(node.func, 'javascript', uri);

    if (model.getValue() !== node.func) {
      model.setValue(node.func);
    }

    const host = editorHost();
    const retained = !!(
      host &&
      typeof host.retainModel === 'function' &&
      typeof host.releaseModel === 'function'
    );
    if (retained) {
      host.retainModel(uri);
    }

    const entry = {
      id: node.id,
      moduleName: node.moduleName,
      uri,
      model,
      source: node.func,
      retained,
    };
    entries[node.id] = entry;
    return entry;
  }

  function propertyName(name) {
    return /^[$A-Z_a-z][$\w]*$/.test(name) ? name : JSON.stringify(name);
  }

  function buildRegistryDeclarations(moduleNodes) {
    const lines = [
      '// Generated by node-red-contrib-module. Do not edit.',
      '// Available before Node-RED finishes loading its server-side globals.',
      'declare var module: { exports: any };',
      'declare var exports: any;',
      'declare function require(moduleName: string): any;',
      '',
    ];

    lines.push('interface NodeRedModuleRegistry {');

    moduleNodes.forEach(function (node) {
      lines.push(
        '    readonly ' +
          propertyName(node.moduleName) +
          ': typeof import("./' +
          node.id +
          '.js");',
      );
    });

    lines.push(
      '}',
      '',
    );
    return lines.join('\n');
  }

  function augmentFunctionTypes(source) {
    if (!source) {
      return null;
    }
    const classDeclaration = 'declare class global {';
    if (source.indexOf(classDeclaration) === -1) {
      return null;
    }
    return source.replace(
      classDeclaration,
      classDeclaration +
        '\n    static get(name: "modules"): NodeRedModuleRegistry;',
    );
  }

  function refreshFunctionTypes() {
    functionTypesTimer = null;
    if (!monacoReady() || !registryLib) {
      return;
    }
    const source = augmentFunctionTypes(functionTypesSource);
    if (!source) {
      return;
    }
    if (functionTypesLib) {
      functionTypesLib.dispose();
    }
    functionTypesLib =
      root.monaco.typescript.javascriptDefaults.addExtraLib(
        source,
        FUNCTION_TYPES_URI,
      );
  }

  function scheduleFunctionTypesRefresh(delay) {
    if (!functionTypesSource || functionTypesTimer) {
      return;
    }
    const setTimer = root.setTimeout || setTimeout;
    functionTypesTimer = setTimer(
      refreshFunctionTypes,
      delay === undefined ? 0 : delay,
    );
  }

  function ensureFunctionTypes() {
    if (functionTypesSource) {
      refreshFunctionTypes();
      return;
    }
    if (
      functionTypesRequest ||
      !root.$ ||
      typeof root.$.get !== 'function'
    ) {
      return;
    }

    functionTypesRequest = root.$
      .get(FUNCTION_TYPES_PATH)
      .done(function (source) {
        functionTypesSource = source;
        functionTypesRequest = null;
        refreshFunctionTypes();
      })
      .fail(function () {
        functionTypesRequest = null;
      });
  }

  function refreshRegistry(moduleNodes, force) {
    const signature = moduleNodes
      .map(function (node) {
        return node.moduleName + '\u0000' + node.id;
      })
      .join('\u0001');

    if (!force && registryLib && signature === registrySignature) {
      return;
    }
    if (registryLib) {
      registryLib.dispose();
    }
    registryLib = root.monaco.typescript.javascriptDefaults.addExtraLib(
      buildRegistryDeclarations(moduleNodes),
      REGISTRY_URI,
    );
    registrySignature = signature;
  }

  function sync() {
    syncTimer = null;
    if (!monacoReady()) {
      return false;
    }

    const moduleNodes = collectModules();
    const desired = Object.create(null);
    let modelsChanged = false;

    moduleNodes.forEach(function (node) {
      desired[node.id] = node;
    });

    Object.keys(entries).forEach(function (nodeId) {
      const entry = entries[nodeId];
      if (!desired[nodeId] || entry.model.isDisposed()) {
        disposeEntry(nodeId);
        modelsChanged = true;
      }
    });

    moduleNodes.forEach(function (node) {
      let entry = entries[node.id];
      if (!entry) {
        entry = createEntry(node);
        modelsChanged = true;
      } else if (entry.source !== node.func) {
        entry.model.setValue(node.func);
        entry.source = node.func;
      }
      entry.moduleName = node.moduleName;
    });

    refreshRegistry(moduleNodes, modelsChanged);
    ensureFunctionTypes();
    return true;
  }

  function scheduleSync(delay) {
    if (syncTimer) {
      return;
    }
    const setTimer = root.setTimeout || setTimeout;
    syncTimer = setTimer(sync, delay === undefined ? 30 : delay);
  }

  function disposeAll() {
    const clearTimer = root.clearTimeout || clearTimeout;
    if (syncTimer) {
      clearTimer(syncTimer);
      syncTimer = null;
    }
    if (functionTypesTimer) {
      clearTimer(functionTypesTimer);
      functionTypesTimer = null;
    }
    Object.keys(entries).forEach(disposeEntry);
    if (registryLib) {
      registryLib.dispose();
      registryLib = null;
    }
    if (functionTypesLib) {
      functionTypesLib.dispose();
      functionTypesLib = null;
    }
    registrySignature = '';
  }

  function register() {
    if (registered || !root.RED || !root.RED.events || !root.RED.nodes) {
      return;
    }
    registered = true;

    ['nodes:add', 'nodes:remove', 'nodes:change', 'flows:loaded'].forEach(
      function (eventName) {
        root.RED.events.on(eventName, function () {
          scheduleSync();
        });
      },
    );
    root.RED.events.on('editor:open', function () {
      scheduleSync(0);
      scheduleFunctionTypesRefresh(400);
    });
    root.RED.events.on('editor:change', function () {
      scheduleSync(0);
      scheduleFunctionTypesRefresh(400);
    });
    root.RED.events.on('workspace:clear', function () {
      disposeAll();
      scheduleSync();
    });
    scheduleSync();
  }

  return {
    register,
    sync,
    scheduleSync,
    dispose: disposeAll,
    buildRegistryDeclarations,
    augmentFunctionTypes,
  };
});
